//! Tiltfile generation from profiles.

use devdock_core::{profile::Profile, Result};
use std::path::Path;

/// Generates Tiltfiles from DevDock profiles.
pub struct TiltfileGenerator;

impl TiltfileGenerator {
    pub fn new() -> Self {
        Self
    }

    /// Generate a Tiltfile from a profile.
    pub fn generate(&self, profile: &Profile, output_dir: &Path) -> Result<String> {
        let mut tiltfile = String::new();

        // Header
        tiltfile.push_str("# Generated by DevDock v2.0.0\n");
        tiltfile.push_str("# DO NOT EDIT - Changes will be overwritten\n\n");

        // Load extensions
        tiltfile.push_str("load('ext://restart_process', 'docker_build_with_restart')\n\n");

        // Setup networks
        tiltfile.push_str("# Setup Docker networks\n");
        tiltfile.push_str("local('docker network create devdock_network || true')\n");
        tiltfile.push_str("local('docker network create devdock_infra || true')\n\n");

        // Infrastructure components
        if !profile.infra.is_empty() {
            tiltfile.push_str("# Infrastructure\n");
            for (name, config) in &profile.infra {
                tiltfile.push_str(&format!(
                    "local_resource('{}', serve_cmd='echo Starting {}')\n",
                    name, name
                ));
            }
            tiltfile.push_str("\n");
        }

        // Services
        if !profile.services.is_empty() {
            tiltfile.push_str("# Services\n");
            for (name, config) in &profile.services {
                tiltfile.push_str(&format!(
                    "local_resource('{}', serve_cmd='echo Starting {}')\n",
                    name, name
                ));
            }
        }

        Ok(tiltfile)
    }
}

impl Default for TiltfileGenerator {
    fn default() -> Self {
        Self::new()
    }
}

