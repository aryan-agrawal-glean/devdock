//! Tiltfile generator for the OSS pipeline.
//!
//! Generates a Tiltfile that:
//! 1. Loads shipped DevDock Starlark libraries from ~/.devdock/lib/
//! 2. References infra compose files (repo override → built-in)
//! 3. Calls setup_service() for each resolved service
//!
//! This replaces the hand-written devdock/Tiltfile and per-service Tiltfiles.

use crate::project_config::ProjectConfig;
use crate::resolver::ResolvedDeps;
use crate::service_config::DevdockServiceConfig;
use std::collections::HashMap;
use std::path::Path;

/// Generate the runtime Tiltfile.
///
/// The generated Tiltfile loads shipped libraries and calls them for each
/// service. Dockerfiles and compose files are generated by the Starlark
/// libraries at Tilt runtime, NOT by this function.
pub fn generate_tiltfile(
    services: &HashMap<String, DevdockServiceConfig>,
    resolved: &ResolvedDeps,
    config: &ProjectConfig,
    project_root: &Path,
) -> String {
    let mut out = String::new();
    let infra_dir = &config.project.infra_dir;

    // Header
    out.push_str(&format!(
        "# Auto-generated by DevDock v{} — do not edit\n",
        env!("CARGO_PKG_VERSION")
    ));
    out.push_str("# Regenerated on each `devdock start`\n\n");

    // Allow any k8s context (DevDock uses Docker, not k8s)
    out.push_str("allow_k8s_contexts(k8s_context())\n\n");

    // Load shipped DevDock libraries
    // Libs are extracted to devdock/runtime_generated/core/lib/ at runtime,
    // mirroring the monorepo layout so relative load() paths work.
    out.push_str("# Load DevDock libraries\n");
    out.push_str("load('ext://restart_process', 'docker_build_with_restart')\n");
    out.push_str("load('./core/lib/service.Tiltfile', 'load_service_config', 'setup_service')\n");
    out.push_str(
        "load('./core/lib/docker.Tiltfile', 'cleanup_generated_files', 'setup_networks')\n",
    );
    out.push_str("load('./core/lib/bazel.Tiltfile', 'bazel_build')\n\n");

    // Settings
    out.push_str("update_settings(max_parallel_updates=10)\n");
    out.push_str("analytics_settings(enable=False)\n\n");

    // Read runtime config
    out.push_str("# Read runtime config\n");
    out.push_str("profile = read_yaml('temp_profile.yaml')\n\n");

    // Docker networks
    out.push_str("# Docker networks\n");
    out.push_str("setup_networks()\n");
    out.push_str(
        "local('docker images --filter \"dangling=true\" -q | xargs -r docker rmi || true')\n\n",
    );

    // Helper resources
    out.push_str("# ─── Helper Resources ───────────────────────────────────────\n\n");

    // Load repo-specific hooks if they exist
    let hooks_dir_path = project_root.join(&config.project.hooks_dir);
    let hooks_rel = format!("../../{}", config.project.hooks_dir);

    // Check for hooks as either {name}/Tiltfile (nested) or {name}.Tiltfile (flat)
    let load_hook = |name: &str| -> Option<String> {
        if hooks_dir_path.join(format!("{name}/Tiltfile")).exists() {
            Some(format!("load_dynamic('{hooks_rel}/{name}/Tiltfile')\n"))
        } else if hooks_dir_path.join(format!("{name}.Tiltfile")).exists() {
            Some(format!("load_dynamic('{hooks_rel}/{name}.Tiltfile')\n"))
        } else {
            None
        }
    };

    if let Some(hook) = load_hook("auth") {
        out.push_str(&hook);
    } else {
        out.push_str(GCLOUD_AUTH_RESOURCE);
    }
    if let Some(hook) = load_hook("misc") {
        out.push_str(&hook);
    }
    if let Some(hook) = load_hook("profile_update") {
        out.push_str(&hook);
    }
    if let Some(hook) = load_hook("observability") {
        out.push_str(&hook);
    } else {
        out.push_str(STARTUP_MONITOR_RESOURCE);
    }
    out.push('\n');

    // Central bazel build (parallel compilation for non-Go services)
    out.push_str("load('./core/lib/central_bazel.Tiltfile', 'setup_central_bazel_build')\n");
    out.push_str("setup_central_bazel_build(profile)\n\n");

    // Infrastructure — load Tiltfiles if available (includes hydrators), fall back to compose.
    // Supports both traditional infra (by well-known name) and unified infra components
    // (kind: infra in devdock_config.json).
    if !resolved.infra.is_empty() {
        out.push_str("# ─── Infrastructure ─────────────────────────────────────────\n\n");
        let mut infra_sorted: Vec<_> = resolved.infra.iter().collect();
        infra_sorted.sort();
        for name in &infra_sorted {
            let infra_tiltfile = project_root.join(format!("{infra_dir}/{name}/Tiltfile"));
            if infra_tiltfile.exists() {
                // Use the repo's infra Tiltfile (includes hydrators, custom setup)
                let tiltfile_path = format!("../../{infra_dir}/{name}/Tiltfile");
                out.push_str(&format!("load_dynamic('{tiltfile_path}')\n\n"));
            } else {
                // Check if we have a devdock_config.json with kind:infra that can generate compose
                let compose_from_config = services.get(name.as_str()).and_then(|svc| {
                    if svc.is_infra() {
                        svc.generate_compose(name)
                    } else {
                        None
                    }
                });

                if let Some(generated_compose) = compose_from_config {
                    // Write generated compose to runtime_generated/infra/{name}/
                    let gen_infra_dir =
                        project_root.join(format!("devdock/runtime_generated/infra/{name}"));
                    let _ = std::fs::create_dir_all(&gen_infra_dir);
                    let compose_file = gen_infra_dir.join("docker-compose.yaml");
                    let _ = std::fs::write(&compose_file, &generated_compose);
                    out.push_str(&format!(
                        "docker_compose('./infra/{name}/docker-compose.yaml')\n"
                    ));
                    out.push_str(&format!("dc_resource('{name}', labels=['infra'])\n\n"));
                } else {
                    // Fall back to shipped or repo compose file
                    let compose_path = resolve_infra_compose(name, infra_dir, project_root);
                    out.push_str(&format!("docker_compose('{compose_path}')\n"));
                    out.push_str(&format!("dc_resource('{name}', labels=['infra'])\n\n"));
                }
            }
        }
    }

    // Services — local services get full setup, remote services get port-forward
    if !resolved.services.is_empty() {
        out.push_str("# ─── Services ───────────────────────────────────────────────\n");
        out.push_str("# Local services: full build + Docker container\n");
        out.push_str("# Remote services: kubectl port-forward to remote endpoint\n\n");
        out.push_str("load('./core/lib/remote_service.Tiltfile', 'setup_remote_service')\n\n");

        for svc_name in &resolved.services {
            if let Some(svc_config) = services.get(svc_name) {
                let services_dir = &config.project.services_dir;
                let port = svc_config.port.as_deref().unwrap_or("8080");

                out.push_str(&format!(
                    "_svc_type = profile.get('services', {{}}).get('{svc_name}', {{}}).get('type', 'remote')\n"
                ));
                out.push_str("if _svc_type == 'local':\n");
                out.push_str(&format!(
                    "    setup_service('{svc_name}', load_service_config('../../{services_dir}/{svc_name}'))\n"
                ));
                out.push_str("else:\n");
                out.push_str(&format!("    setup_remote_service('{svc_name}', {port})\n"));
                out.push('\n');
            }
        }
    }

    out
}

/// Resolve the compose file path for an infra component.
/// Resolution: repo override → built-in default.
fn resolve_infra_compose(name: &str, infra_dir: &str, project_root: &Path) -> String {
    // Check repo override first
    let repo_path = project_root.join(format!("{infra_dir}/{name}/docker-compose.yaml"));
    if repo_path.exists() {
        // Path relative to devdock/runtime_generated/ (where Tiltfile lives)
        return format!("../../{infra_dir}/{name}/docker-compose.yaml");
    }
    // Fall back to built-in (shipped with devdock binary)
    let home = std::env::var("HOME").unwrap_or_else(|_| "~".into());
    format!("{home}/.devdock/lib/infra/{name}/docker-compose.yaml")
}

/// Extract shipped Starlark libraries to the runtime_generated directory.
///
/// Writes to `{workspace_root}/devdock/runtime_generated/core/lib/` and
/// `{workspace_root}/devdock/runtime_generated/core/templates/` so that
/// relative `load()` paths in Starlark work correctly.
///
/// Also creates service_hooks stub if not present in the repo.
pub fn extract_shipped_libs_to(workspace_root: &Path) -> std::io::Result<()> {
    let runtime_dir = workspace_root.join("devdock/runtime_generated");
    let lib_dir = runtime_dir.join("core/lib");
    let templates_dir = runtime_dir.join("core/templates");
    let infra_dir = runtime_dir.join("infra");

    std::fs::create_dir_all(&lib_dir)?;
    std::fs::create_dir_all(&infra_dir)?;
    std::fs::create_dir_all(&templates_dir)?;

    // Check version marker — skip extraction if already up to date
    let version = env!("CARGO_PKG_VERSION");
    let version_file = runtime_dir.join(".lib_version");
    if version_file.exists() {
        if let Ok(existing) = std::fs::read_to_string(&version_file) {
            if existing.trim() == version {
                return Ok(()); // Already up to date
            }
        }
    }

    // Extract Starlark libraries (embedded in binary via include_str!)
    write_embedded(&lib_dir, "service.Tiltfile", include_str!("../../../lib/service.Tiltfile"))?;
    write_embedded(&lib_dir, "docker.Tiltfile", include_str!("../../../lib/docker.Tiltfile"))?;
    write_embedded(&lib_dir, "bazel.Tiltfile", include_str!("../../../lib/bazel.Tiltfile"))?;
    write_embedded(&lib_dir, "utils.Tiltfile", include_str!("../../../lib/utils.Tiltfile"))?;
    write_embedded(
        &lib_dir,
        "hot_reload.Tiltfile",
        include_str!("../../../lib/hot_reload.Tiltfile"),
    )?;
    write_embedded(
        &lib_dir,
        "central_bazel.Tiltfile",
        include_str!("../../../lib/central_bazel.Tiltfile"),
    )?;
    write_embedded(
        &lib_dir,
        "remote_service.Tiltfile",
        include_str!("../../../lib/remote_service.Tiltfile"),
    )?;
    write_embedded(
        &lib_dir,
        "pipelines.Tiltfile",
        include_str!("../../../lib/pipelines.Tiltfile"),
    )?;
    write_embedded(
        &lib_dir,
        "test_suite.Tiltfile",
        include_str!("../../../lib/test_suite.Tiltfile"),
    )?;
    write_embedded(&lib_dir, "logger.Tiltfile", include_str!("../../../lib/logger.Tiltfile"))?;

    // Extract templates
    write_embedded(
        &templates_dir,
        "Dockerfile.python.tpl",
        include_str!("../../../lib/templates/Dockerfile.python.tpl"),
    )?;
    write_embedded(
        &templates_dir,
        "Dockerfile.go.tpl",
        include_str!("../../../lib/templates/Dockerfile.go.tpl"),
    )?;
    write_embedded(
        &templates_dir,
        "Dockerfile.tpl",
        include_str!("../../../lib/templates/Dockerfile.tpl"),
    )?;
    write_embedded(
        &templates_dir,
        "compose.yaml.tpl",
        include_str!("../../../lib/templates/compose.yaml.tpl"),
    )?;

    // Copy shipped libs into devdock/core/lib/ so that infra Tiltfiles and
    // helper Tiltfiles can find them via relative paths like:
    //   load('../../../core/lib/bazel.Tiltfile', ...)
    //   load('../../../core/lib/utils.Tiltfile', ...)
    let devdock_core_lib = workspace_root.join("devdock/core/lib");
    std::fs::create_dir_all(&devdock_core_lib)?;
    // Copy each shipped Tiltfile into core/lib/ (alongside any existing files)
    for entry in std::fs::read_dir(lib_dir.as_path())? {
        let entry = entry?;
        let src = entry.path();
        if src.extension().and_then(|e| e.to_str()) == Some("Tiltfile") {
            let dest = devdock_core_lib.join(entry.file_name());
            std::fs::copy(&src, &dest)?;
        }
    }

    // Same for templates
    let devdock_core_templates = workspace_root.join("devdock/core/templates");
    std::fs::create_dir_all(&devdock_core_templates)?;
    for entry in std::fs::read_dir(templates_dir.as_path())? {
        let entry = entry?;
        let dest = devdock_core_templates.join(entry.file_name());
        std::fs::copy(entry.path(), &dest)?;
    }

    // Create service_hooks stub (or symlink to repo if exists)
    let hooks_dir = runtime_dir.join("config/services/service_hooks");
    std::fs::create_dir_all(&hooks_dir)?;
    let repo_hooks = workspace_root.join("devdock/config/services/service_hooks/Tiltfile");
    let stub_hooks = hooks_dir.join("Tiltfile");
    if repo_hooks.exists() {
        // Symlink to repo's actual hooks
        if stub_hooks.exists() {
            std::fs::remove_file(&stub_hooks)?;
        }
        #[cfg(unix)]
        std::os::unix::fs::symlink(&repo_hooks, &stub_hooks)?;
        #[cfg(not(unix))]
        std::fs::copy(&repo_hooks, &stub_hooks)?;
    } else if !stub_hooks.exists() {
        // Write a no-op stub
        std::fs::write(&stub_hooks, "def get_pre_service_hooks(name):\n    return []\n")?;
    }

    // Extract default infra compose files
    for (name, content) in DEFAULT_INFRA_COMPOSE {
        let dir = infra_dir.join(name);
        std::fs::create_dir_all(&dir)?;
        std::fs::write(dir.join("docker-compose.yaml"), content)?;
    }

    // Write version marker
    std::fs::write(&version_file, version)?;

    Ok(())
}

const GCLOUD_AUTH_RESOURCE: &str = r#"# GCloud auth — copies ADC credentials for Docker registry access
local_resource(
    name='init-gcloud-auth',
    cmd='''
    if [ -f ~/.config/gcloud/application_default_credentials.json ]; then
        mkdir -p ~/.devdock/auth/
        rsync -rltD -L ~/.config/gcloud/application_default_credentials.json ~/.devdock/auth/
    fi
    ''',
    allow_parallel=True,
    labels=['devdock-core'],
)
"#;

const STARTUP_MONITOR_RESOURCE: &str = r#"# Startup monitor — tracks service health
_services = profile.get('services', {})
_infra = profile.get('infra', {})
_monitor_deps = ['{}-bazel-build'.format(s) for s in _services.keys() if type(_services[s]) == 'dict' and _services[s].get('type', 'local') == 'local'] + [i for i in _infra.keys()]
local_resource(
    name='startup-monitor',
    labels=['devdock-core'],
    cmd=['devdock', 'monitor'],
    resource_deps=_monitor_deps,
    allow_parallel=True,
)
"#;

fn write_embedded(dir: &Path, name: &str, content: &str) -> std::io::Result<()> {
    std::fs::write(dir.join(name), content)
}

