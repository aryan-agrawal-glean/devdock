#[cfg(test)]
mod tests {
    use super::*;

    fn test_config() -> ProjectConfig {
        ProjectConfig::parse("[project]\nname = \"test\"").unwrap()
    }

    fn svc(deps: &[&str]) -> DevdockServiceConfig {
        DevdockServiceConfig::parse(
            &serde_json::json!({"type":"python","dependencies":deps}).to_string(),
        )
        .unwrap()
    }

    #[test]
    fn tiltfile_has_header() {
        let tf = generate_tiltfile(
            &HashMap::new(),
            &ResolvedDeps { services: vec![], infra: vec![] },
            &test_config(),
            Path::new("/tmp"),
        );
        assert!(tf.contains("Auto-generated by DevDock"));
        assert!(tf.contains("allow_k8s_contexts"));
    }

    #[test]
    fn tiltfile_loads_shipped_libs() {
        let tf = generate_tiltfile(
            &HashMap::new(),
            &ResolvedDeps { services: vec![], infra: vec![] },
            &test_config(),
            Path::new("/tmp"),
        );
        assert!(tf.contains("~/.devdock/lib"));
        assert!(tf.contains("service.Tiltfile"));
        assert!(tf.contains("docker.Tiltfile"));
        assert!(tf.contains("bazel.Tiltfile"));
    }

    #[test]
    fn tiltfile_has_networks() {
        let tf = generate_tiltfile(
            &HashMap::new(),
            &ResolvedDeps { services: vec![], infra: vec![] },
            &test_config(),
            Path::new("/tmp"),
        );
        assert!(tf.contains("devdock_network"));
        assert!(tf.contains("devdock_infra"));
    }

    #[test]
    fn tiltfile_infra_before_services() {
        let mut svcs = HashMap::new();
        svcs.insert("api".into(), svc(&["sql"]));
        let resolved = ResolvedDeps { services: vec!["api".into()], infra: vec!["sql".into()] };
        let tf = generate_tiltfile(&svcs, &resolved, &test_config(), Path::new("/tmp"));
        let infra_pos = tf.find("dc_resource('sql'").unwrap();
        let svc_pos = tf.find("setup_service('api'").unwrap();
        assert!(infra_pos < svc_pos);
    }

    #[test]
    fn tiltfile_service_with_deps() {
        let mut svcs = HashMap::new();
        svcs.insert("api".into(), svc(&["sql", "redis"]));
        let resolved = ResolvedDeps {
            services: vec!["api".into()],
            infra: vec!["sql".into(), "redis".into()],
        };
        let tf = generate_tiltfile(&svcs, &resolved, &test_config(), Path::new("/tmp"));
        assert!(tf.contains("'resource_deps': ['sql', 'redis']"));
    }

    #[test]
    fn extract_creates_version_marker() {
        let dir = tempfile::tempdir().unwrap();
        std::env::set_var("HOME", dir.path());
        extract_shipped_libs().unwrap();
        assert!(dir.path().join(".devdock/lib/.version").exists());
        assert!(dir.path().join(".devdock/lib/service.Tiltfile").exists());
        assert!(dir.path().join(".devdock/lib/infra/sql/docker-compose.yaml").exists());
        std::env::remove_var("HOME");
    }
}
