//! Integration tests running the full pipeline against fixture repos.

use devdock_core::profile::Profile;
use devdock_core::project_config::ProjectConfig;
use devdock_core::resolver;
use devdock_core::service_config::discover_services;
use devdock_core::tiltfile_generator;
use std::path::{Path, PathBuf};

fn fixtures_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap().parent().unwrap().join("tests/fixtures")
}

fn run_pipeline(
    fixture_name: &str,
    profile_name: &str,
) -> (String, devdock_core::resolver::ResolvedDeps) {
    let fixture = fixtures_dir().join(fixture_name);
    let config = ProjectConfig::load(&fixture.join(".devdock/devdock.toml")).unwrap();
    let services = discover_services(&fixture.join(&config.project.services_dir)).unwrap();

    let profile_path = fixture.join(format!(".devdock/profiles/{profile_name}.yaml"));
    let profile_content = std::fs::read_to_string(&profile_path).unwrap();
    let profile_yaml: serde_yaml::Value = serde_yaml::from_str(&profile_content).unwrap();

    let mut requested = Vec::new();
    if let Some(svcs) = profile_yaml.get("services").and_then(|s| s.as_mapping()) {
        for (name, _) in svcs {
            if let Some(s) = name.as_str() {
                requested.push(s.to_string());
            }
        }
    }
    if let Some(infra) = profile_yaml.get("infra").and_then(|s| s.as_mapping()) {
        for (name, _) in infra {
            if let Some(s) = name.as_str() {
                requested.push(s.to_string());
            }
        }
    }

    let resolved = resolver::resolve(&requested, &services).unwrap();
    let profile: Profile = serde_yaml::from_str(&profile_content).unwrap_or_else(|_| Profile {
        project: "test".into(),
        platform: devdock_core::types::Platform::None,
        infra: std::collections::HashMap::new(),
        services: std::collections::HashMap::new(),
        pipelines: std::collections::HashMap::new(),
        test_suite: std::collections::HashMap::new(),
        env: std::collections::HashMap::new(),
        ini_overrides: vec![],
        multi_project: None,
        dns_kubectl: None,
    });
    let tiltfile =
        tiltfile_generator::generate_tiltfile(&services, &resolved, &config, &fixture, &profile);
    (tiltfile, resolved)
}

// ─── minimal-python ────────────────────────────────────────────────────────────

#[test]
fn minimal_python_pipeline() {
    let (tf, resolved) = run_pipeline("minimal-python", "default");
    assert_eq!(resolved.services.len(), 1);
    assert!(resolved.services.contains(&"api".to_string()));
    assert!(resolved.infra.is_empty());
    assert!(tf.contains("setup_service('api'"));
    assert!(tf.contains("Auto-generated by DevDock"));
}

// ─── multi-service ─────────────────────────────────────────────────────────────

#[test]
fn multi_service_default_profile() {
    let (tf, resolved) = run_pipeline("multi-service", "default");
    assert_eq!(resolved.services.len(), 3);
    assert!(resolved.infra.contains(&"sql".to_string()));
    assert!(resolved.infra.contains(&"redis".to_string()));
    assert!(tf.contains("setup_service('api'"));
    assert!(tf.contains("setup_service('worker'"));
    assert!(tf.contains("setup_service('frontend'"));
}

#[test]
fn multi_service_minimal_profile() {
    let (_, resolved) = run_pipeline("multi-service", "minimal");
    assert_eq!(resolved.services.len(), 1);
    assert!(resolved.services.contains(&"api".to_string()));
    // Transitive infra deps still discovered
    assert!(resolved.infra.contains(&"sql".to_string()));
    assert!(resolved.infra.contains(&"redis".to_string()));
}

#[test]
fn multi_service_dependency_order() {
    let (_, resolved) = run_pipeline("multi-service", "default");
    let api_pos = resolved.services.iter().position(|s| s == "api").unwrap();
    let worker_pos = resolved.services.iter().position(|s| s == "worker").unwrap();
    let fe_pos = resolved.services.iter().position(|s| s == "frontend").unwrap();
    assert!(api_pos < worker_pos, "api must come before worker");
    assert!(api_pos < fe_pos, "api must come before frontend");
}

// ─── with-infra ────────────────────────────────────────────────────────────────

#[test]
fn with_infra_local_profile() {
    let (tf, resolved) = run_pipeline("with-infra", "local");
    assert_eq!(resolved.services.len(), 1);
    assert_eq!(resolved.infra.len(), 3);
    assert!(resolved.infra.contains(&"sql".to_string()));
    assert!(resolved.infra.contains(&"redis".to_string()));
    assert!(resolved.infra.contains(&"opensearch".to_string()));
    // Infra appears before services in Tiltfile
    let infra_pos = tf.find("Infrastructure").unwrap();
    let svc_pos = tf.find("Services").unwrap();
    assert!(infra_pos < svc_pos);
}

// ─── Tiltfile structure ────────────────────────────────────────────────────────

#[test]
fn tiltfile_has_required_sections() {
    let (tf, _) = run_pipeline("multi-service", "default");
    assert!(tf.contains("allow_k8s_contexts"));
    assert!(tf.contains("service.Tiltfile"));
    assert!(tf.contains("docker.Tiltfile"));
    assert!(tf.contains("bazel.Tiltfile"));
    assert!(tf.contains("setup_networks()"));
    assert!(tf.contains("init-gcloud-auth"));
    assert!(tf.contains("central_bazel"));
    assert!(tf.contains("temp_profile.yaml"));
}

#[test]
fn tiltfile_setup_service_calls_load_config() {
    let (tf, _) = run_pipeline("minimal-python", "default");
    assert!(tf.contains("load_service_config("));
    assert!(tf.contains("setup_service('api', load_service_config("));
}

// ─── Shipped lib extraction ────────────────────────────────────────────────────

#[test]
fn extract_libs_creates_all_files() {
    let dir = tempfile::tempdir().unwrap();
    std::fs::create_dir_all(dir.path().join("devdock/runtime_generated")).unwrap();
    tiltfile_generator::extract_shipped_libs_to(dir.path()).unwrap();

    // Core libs
    assert!(dir.path().join("devdock/runtime_generated/core/lib/service.Tiltfile").exists());
    assert!(dir.path().join("devdock/runtime_generated/core/lib/docker.Tiltfile").exists());
    assert!(dir.path().join("devdock/runtime_generated/core/lib/bazel.Tiltfile").exists());
    assert!(dir.path().join("devdock/runtime_generated/core/lib/central_bazel.Tiltfile").exists());

    // Templates
    assert!(dir
        .path()
        .join("devdock/runtime_generated/core/templates/Dockerfile.python.tpl")
        .exists());
    assert!(dir.path().join("devdock/runtime_generated/core/templates/Dockerfile.go.tpl").exists());
    assert!(dir.path().join("devdock/runtime_generated/core/templates/compose.yaml.tpl").exists());

    // Service hooks stub
    assert!(dir.path().join("devdock/runtime_generated/services/service_hooks/Tiltfile").exists());

    // Default infra
    assert!(dir.path().join("devdock/runtime_generated/infra/sql/docker-compose.yaml").exists());
    assert!(dir.path().join("devdock/runtime_generated/infra/redis/docker-compose.yaml").exists());

    // Version marker
    assert!(dir.path().join("devdock/runtime_generated/.lib_version").exists());
}
